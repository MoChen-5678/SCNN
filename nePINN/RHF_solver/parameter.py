def list_param_sets():
    """返回所有可用参数集名称"""
    return list(_PARAM_SETS.keys())


def get_param_set(name: str):
    """返回指定参数集的字典"""
    if name not in _PARAM_SETS:
        raise ValueError(f"参数集 {name} 不存在，可选项：{list(_PARAM_SETS.keys())}")
    return _PARAM_SETS[name].copy()
